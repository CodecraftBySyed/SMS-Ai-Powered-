CREATE TRIGGER update_status_after_attendance 
AFTER INSERT ON attendance
FOR EACH ROW
BEGIN
    DECLARE avg_att DECIMAL(5,2);
    DECLARE bal DECIMAL(10,2);
    DECLARE new_status VARCHAR(50);
    
    -- Calculate average attendance for the student
    SELECT (SUM(present) / COUNT(*)) * 100 INTO avg_att 
    FROM attendance WHERE student_id = NEW.student_id;
    
    -- Get balance
    SELECT balance_fee INTO bal FROM students WHERE id = NEW.student_id;
    
    -- Determine Status
    IF avg_att < 75 OR bal > 10000 THEN
        SET new_status = 'Needs Attention';
    ELSEIF avg_att > 85 AND bal = 0 THEN
        SET new_status = 'Good';
    ELSE
        SET new_status = 'Average';
    END IF;
    
    -- Update Student
    UPDATE students SET status = new_status WHERE id = NEW.student_id;
END;
