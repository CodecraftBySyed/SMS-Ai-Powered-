CREATE TRIGGER update_status_before_student_update
BEFORE UPDATE ON students
FOR EACH ROW
BEGIN
    DECLARE avg_att DECIMAL(5,2);
    DECLARE new_status VARCHAR(50);
    
    -- Only run if balance or fees changed
    IF NEW.balance_fee != OLD.balance_fee OR NEW.paid_fee != OLD.paid_fee THEN
        -- Calculate average attendance
        SELECT (SUM(present) / COUNT(*)) * 100 INTO avg_att 
        FROM attendance WHERE student_id = NEW.id;
        
        -- Handle case where no attendance yet
        IF avg_att IS NULL THEN
            SET avg_att = 100; -- Assume good if new
        END IF;

        -- Determine Status
        IF avg_att < 75 OR NEW.balance_fee > 10000 THEN
            SET new_status = 'Needs Attention';
        ELSEIF avg_att > 85 AND NEW.balance_fee = 0 THEN
            SET new_status = 'Good';
        ELSE
            SET new_status = 'Average';
        END IF;
        
        SET NEW.status = new_status;
    END IF;
END;
